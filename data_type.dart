// Numbers, String, booleans, lists, maps, dynamic




void main(){

  // Strings/
  String First_name = "Anasri";
  print("My First name is : $First_name");

  // int
  int integer = 41;
  print("The integer value is : $integer");

  //double
  double d = 33.33;
  print("The double value is : $d");

  // num 
  num num1 = 44.44;
  num num2 = 44;
  print("First num is : $num1");
  print("Second num is : $num2");

  // Boolean
  bool Mybool = true;
  print("The Boolean value is : $Mybool");

  // Dynamic
  dynamic fullname = "razzaq";
  dynamic dynamic_integer = 41;
  dynamic dynamic_boolans = true;
  print("$dynamic_boolans $dynamic_integer $fullname");

}